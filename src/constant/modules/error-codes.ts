export type TErrorCode = keyof typeof ERROR_CODES

/**
 * 获取错误消息
 * @param code 错误码
 * @returns 对应的错误消息
 */
export function getErrorMessage(code: TErrorCode | string | number): string {
  const errorCode = String(code)
  return (ERROR_CODES as Record<string, string>)[errorCode] || '系统错误，请稍后重试'
}

/**
 * 判断是否为已知的错误码
 * @param code 错误码
 * @returns 是否为已知错误码
 */
export function isKnownErrorCode(code: TErrorCode | string | number): code is TErrorCode {
  const errorCode = String(code)
  return errorCode in ERROR_CODES
}
